package com.techinsights.domain.repository

import com.techinsights.domain.support.RepositoryTestSpec
import io.kotest.matchers.shouldBe
import org.springframework.core.io.ClassPathResource
import org.springframework.jdbc.core.JdbcTemplate
import org.springframework.transaction.support.TransactionTemplate

/**
 * V027 must work whether the id columns were created as BIGSERIAL (Flyway B001) or as an identity
 * column (Hibernate-created before Flyway). Each shape is rebuilt inside a transaction that is rolled back.
 */
class TsidMigrationShapesTest(
  private val jdbc: JdbcTemplate,
  private val transactionTemplate: TransactionTemplate
) : RepositoryTestSpec({

  val tables = listOf("anonymous_user_read_history", "post_summary_failures")
  val script = ClassPathResource("db/migration/V027__Drop_Serial_Ids_For_Tsid.sql")
    .inputStream.bufferedReader().readText()

  fun idColumnState(table: String): Pair<String?, String> = jdbc.queryForObject(
    "SELECT column_default, is_identity FROM information_schema.columns WHERE table_name = ? AND column_name = 'id'",
    { rs, _ -> rs.getString(1) to rs.getString(2) }, table
  )!!

  fun sequenceExists(name: String) =
    jdbc.queryForObject("SELECT count(*) FROM pg_class WHERE relkind = 'S' AND relname = ?", Int::class.java, name)!! > 0

  fun inRolledBackTransaction(block: () -> Unit) {
    transactionTemplate.execute { status ->
      block()
      status.setRollbackOnly()
    }
  }

  test("the applied migration left no default, identity or sequence on the id columns") {
    tables.forEach {
      idColumnState(it) shouldBe (null to "NO")
      sequenceExists("${it}_id_seq") shouldBe false
    }
  }

  test("the script drops a BIGSERIAL-style default and its sequence") {
    inRolledBackTransaction {
      tables.forEach {
        jdbc.execute("CREATE SEQUENCE ${it}_id_seq OWNED BY $it.id")
        jdbc.execute("ALTER TABLE $it ALTER COLUMN id SET DEFAULT nextval('${it}_id_seq')")
      }

      jdbc.execute(script)

      tables.forEach {
        idColumnState(it) shouldBe (null to "NO")
        sequenceExists("${it}_id_seq") shouldBe false
      }
    }
  }

  test("the script drops an identity column definition and its sequence") {
    inRolledBackTransaction {
      tables.forEach { jdbc.execute("ALTER TABLE $it ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY") }
      tables.forEach { idColumnState(it).second shouldBe "YES" }

      jdbc.execute(script)

      tables.forEach {
        idColumnState(it) shouldBe (null to "NO")
        sequenceExists("${it}_id_seq") shouldBe false
      }
    }
  }

  test("the script is a no-op when the columns are already plain bigint") {
    inRolledBackTransaction {
      jdbc.execute(script)

      tables.forEach { idColumnState(it) shouldBe (null to "NO") }
    }
  }
})
